/**
 * @file    scheduler_cfg.h
 * @brief   Build-time configuration of the cooperative scheduler.
 *          Target: NXP S32K344, RTD 6.0.0, S32 Design Studio.
 *
 * Everything that depends on S32 Config Tools generated names lives here,
 * so scheduler.c never has to change when you rename things in the GUI.
 */
#ifndef SCHEDULER_CFG_H
#define SCHEDULER_CFG_H

#include "Std_Types.h"
#include "Gpt.h"          /* brings in the generated GptConf_... channel symbols */

/* ------------------------------------------------------------------------- */
/* Tick timer (Gpt driver, PIT_0 channel)                                    */
/* ------------------------------------------------------------------------- */

/** Symbolic name of the Gpt channel generated by S32 Config Tools.
 *  Check Gpt_Cfg.h / Gpt_PBcfg.h after "Update Code" for the exact name. */
#define SCHED_GPT_CHANNEL        GptConf_GptChannelConfiguration_GptChannelConfiguration_0

/** PIT input clock in Hz. On S32K344 the PIT runs from AIPS_SLOW_CLK,
 *  40 MHz in the default clock config. Check it in the Clocks tool. */
#define SCHED_PIT_CLOCK_HZ       40000000UL

/** Scheduler tick length in ms. Keep 1 ms unless you have a reason. */
#define SCHED_TICK_MS            1UL

/** Gpt target value for one tick. */
#define SCHED_GPT_TICKS          ((SCHED_PIT_CLOCK_HZ / 1000UL) * SCHED_TICK_MS)

/* ------------------------------------------------------------------------- */
/* CPU / measurement                                                         */
/* ------------------------------------------------------------------------- */

/** Core clock in Hz (Cortex-M7 CORE_CLK). 160 MHz in the default config. */
#define SCHED_CPU_HZ             160000000UL

/** CPU load is computed over this window (ms). The busy-cycle accumulator
 *  is 32 bit: window * (SCHED_CPU_HZ/1000) must stay below 2^32
 *  (1000 ms @ 160 MHz = 1.6e8 -> OK). */
#define SCHED_LOAD_WINDOW_MS     1000UL

/** Maximum number of tasks (alive-supervision mask is 32 bit). */
#define SCHED_MAX_TASKS          32U

/* ------------------------------------------------------------------------- */
/* Interrupt installation                                                    */
/* ------------------------------------------------------------------------- */

/** STD_OFF: PIT0 IRQ + handler PIT_0_ISR are enabled in the Platform
 *           component (Interrupt Controller tab) -> Platform_Init() does it.
 *  STD_ON:  scheduler installs/enables the handler itself via IntCtrl_Ip. */
#define SCHED_INSTALL_IRQ_MANUALLY   STD_OFF

/* ------------------------------------------------------------------------- */
/* Hooks                                                                     */
/* ------------------------------------------------------------------------- */

/** Called when every task has run at least once since the previous call
 *  (alive supervision). Put your watchdog refresh here, e.g. Wdg_SetTriggerCondition().
 *  The watchdog timeout must be longer than the slowest task period.
 *  Do not kick the watchdog from the tick ISR: the ISR keeps running even
 *  when the main loop is stuck, so the watchdog would never fire. */
#ifndef SCHED_WDG_SERVICE
#define SCHED_WDG_SERVICE()      do { } while (0)
#endif

/** Called on every idle pass of the main loop (nothing due).
 *  You can put __asm volatile ("wfi") here to save power; the next PIT
 *  tick wakes the core. */
#ifndef SCHED_IDLE_HOOK
#define SCHED_IDLE_HOOK()        do { } while (0)
#endif

/** Called when a task misses one or more of its release times. */
#ifndef SCHED_OVERRUN_HOOK
#define SCHED_OVERRUN_HOOK(taskIdx)  do { (void)(taskIdx); } while (0)
#endif

#endif /* SCHEDULER_CFG_H */
